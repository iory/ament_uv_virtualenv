"""Hide system packages whose NumPy extensions cannot load in this venv.

Run with the venv's own interpreter after ``uv pip sync``:

    <venv>/bin/python numpy_abi_guard.py

A venv made with ``--system-site-packages`` (the default here, so rclpy and
the rest of ROS stay importable) also sees every apt Python package. When the
venv pins NumPy 2 and the distro ships NumPy 1, an apt package with a compiled
NumPy extension -- python3-shapely, python3-scipy, python3-h5py -- is found
whenever the venv has no copy of its own, and importing it prints NumPy's "A
module that was compiled using NumPy 1.x cannot be run in NumPy 2" traceback
before failing. trimesh imports shapely whenever it can, so every script that
loads a mesh printed that wall, although nothing was actually wrong with it.

Such a package cannot work in this venv at all. This writes an import hook
that makes it unimportable from the venv with a ModuleNotFoundError that says
why and how to get a working copy; code that imports it optionally (trimesh)
then sees it as absent, which is exactly what it is. Nothing is hidden when the
two NumPy major versions agree, and a package the venv installs itself is never
touched -- its own copy comes first on sys.path anyway.

The extension check reads each system ``.so`` for ``_ARRAY_API``, the name of
the capsule ``import_array()`` fetches from NumPy: an extension without it does
not use NumPy's C API and loads under either NumPy.
"""

import importlib.metadata
import mmap
import os
import site
import sys
import sysconfig

GUARD_MODULE = "_ament_uv_numpy_abi_guard"
MARKER = b"_ARRAY_API"


def _numpy_version(paths):
    for dist in importlib.metadata.distributions(path=paths):
        if (dist.metadata["Name"] or "").lower() == "numpy":
            return dist.version
    return None


def _uses_numpy_c_api(path):
    try:
        with open(path, "rb") as handle:
            if os.fstat(handle.fileno()).st_size == 0:
                return False
            with mmap.mmap(handle.fileno(), 0, access=mmap.ACCESS_READ) as data:
                return data.find(MARKER) != -1
    except OSError:
        return False


def _top_level_entries(directory):
    """``{importable top-level name: [extension paths under it]}``."""
    out = {}
    for entry in sorted(os.listdir(directory)):
        full = os.path.join(directory, entry)
        if entry.endswith(".so"):
            out.setdefault(entry.split(".")[0], []).append(full)
        elif (os.path.isdir(full) and entry.isidentifier()
              and not entry.endswith((".dist-info", ".egg-info"))):
            out.setdefault(entry, [])
            for root, _, files in os.walk(full):
                out[entry].extend(os.path.join(root, f) for f in files
                                  if f.endswith(".so"))
    return out


def main():
    venv_site = sysconfig.get_paths()["purelib"]
    guard_py = os.path.join(venv_site, GUARD_MODULE + ".py")
    guard_pth = os.path.join(venv_site, GUARD_MODULE + ".pth")
    for stale in (guard_py, guard_pth):
        if os.path.exists(stale):
            os.remove(stale)

    system_dirs = [d for d in site.getsitepackages()
                   if not d.startswith(sys.prefix) and os.path.isdir(d)]
    venv_numpy = _numpy_version([venv_site])
    system_numpy = _numpy_version(system_dirs)
    if venv_numpy is None or system_numpy is None:
        return
    if venv_numpy.split(".")[0] == system_numpy.split(".")[0]:
        return

    in_venv = set(_top_level_entries(venv_site))
    blocked = {}
    for directory in system_dirs:
        for name, extensions in _top_level_entries(directory).items():
            if name in in_venv or name in blocked or name == "numpy":
                continue
            if any(_uses_numpy_c_api(path) for path in extensions):
                blocked[name] = directory
    if not blocked:
        return

    with open(guard_py, "w") as handle:
        handle.write(GUARD_TEMPLATE.format(
            blocked=repr(blocked), venv_numpy=venv_numpy,
            system_numpy=system_numpy))
    with open(guard_pth, "w") as handle:
        handle.write("import {}\n".format(GUARD_MODULE))
    print("[ament_uv_virtualenv] the venv has NumPy {} but the system has "
          "NumPy {}; hiding system packages built against the latter (add one "
          "to requirements.in to use it here): {}".format(
              venv_numpy, system_numpy, ", ".join(sorted(blocked))))


GUARD_TEMPLATE = '''"""Generated by ament_uv_virtualenv (numpy_abi_guard.py). DO NOT EDIT.

These system packages were built against NumPy {system_numpy}; this venv has
NumPy {venv_numpy}, under which their extensions cannot load.
"""

import importlib.abc
import sys

BLOCKED = {blocked}


class _NumpyAbiGuard(importlib.abc.MetaPathFinder):
    def find_spec(self, fullname, path=None, target=None):
        top = fullname.partition(".")[0]
        if top in BLOCKED:
            raise ModuleNotFoundError(
                "{{}} is only installed system-wide ({{}}), built against "
                "NumPy {system_numpy}; this venv has NumPy {venv_numpy}, which "
                "cannot load it. Add it to the package's requirements.in to "
                "get a build that matches.".format(top, BLOCKED[top]),
                name=fullname)
        return None


sys.meta_path.insert(0, _NumpyAbiGuard())
'''


if __name__ == "__main__":
    main()
